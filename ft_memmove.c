#include "libft.h"

void	*ft_memmove(void *dst, const void *src, size_t len)
{
	char		*d;
	const char	*s;

	d = (char *)dst;
	s = (const char *)src;
	if (d > s)
	{
		while (len--)
			d[len] = s[len];
		return (dst);
	}
	return (ft_memcpy(dst, src, len));
}
